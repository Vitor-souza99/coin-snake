  coins.map((coin) => ({
    ...coin,
    weight: Math.max(0, coin.weight + ({ normal: -40, blue: 24, diamond: 12, golden: 3, mythic: 1 }[coin.id as "normal" | "blue" | "diamond" | "golden" | "mythic"] ?? 0)),
  }));
